#!/usr/bin/env python3
"""Vendor pinned Lucide SVGs as paths for the existing engine icon renderer.

Usage: python3 scripts/import-lucide.py [lucide-static-1.76.0.tgz]
No build-time or runtime icon package is required by engine consumers.
"""
import base64
import hashlib
import io
import json
from pathlib import Path
import re
import sys
import subprocess
import tarfile
import urllib.request
import xml.etree.ElementTree as ET

VERSION = '1.76.0'
INTEGRITY = '8izOkC4xBdjtiIF641S1a21rEZP2DXiAcaRFYMXxwxnaFmgUUqLgelmRMxrNenjuW2pUJZIXEpOMuUcVyadF5Q=='
URL = f'https://registry.npmjs.org/lucide-static/-/lucide-static-{VERSION}.tgz'
archive = Path(sys.argv[1]).read_bytes() if len(sys.argv) > 1 else urllib.request.urlopen(URL).read()
if base64.b64encode(hashlib.sha512(archive).digest()).decode() != INTEGRITY:
    raise ValueError('Lucide archive integrity mismatch')


def num(value):
    return format(float(value), '.12g')


def path(element):
    tag = element.tag.split('}')[-1]
    a = element.attrib
    allowed = {'d', 'cx', 'cy', 'r', 'rx', 'ry', 'x', 'y', 'x1', 'y1', 'x2', 'y2', 'width', 'height', 'points', 'fill'}
    if set(a) - allowed:
        raise ValueError(f'Unsupported {tag} attributes: {a}')
    # Lucide's only explicit fills are radius-.5 dots, already filled by their 2-unit stroke.
    if 'fill' in a and not (tag == 'circle' and float(a['r']) <= 1 and a['fill'] == 'currentColor'):
        raise ValueError(f'Unsupported filled shape: {a}')
    if tag == 'path':
        return a['d']
    if tag in {'circle', 'ellipse'}:
        cx, cy = float(a['cx']), float(a['cy'])
        rx, ry = (float(a['r']), float(a['r'])) if tag == 'circle' else (float(a['rx']), float(a['ry']))
        return f'M{num(cx-rx)} {num(cy)}a{num(rx)} {num(ry)} 0 1 0 {num(2*rx)} 0a{num(rx)} {num(ry)} 0 1 0 {num(-2*rx)} 0Z'
    if tag == 'line':
        return f'M{a["x1"]} {a["y1"]}L{a["x2"]} {a["y2"]}'
    if tag in {'polyline', 'polygon'}:
        points = re.split(r'[\s,]+', a['points'].strip())
        if len(points) % 2:
            raise ValueError('Invalid points')
        return 'M' + 'L'.join(' '.join(points[i:i+2]) for i in range(0, len(points), 2)) + ('Z' if tag == 'polygon' else '')
    if tag == 'rect':
        x, y, w, h = (float(a.get(k, 0)) for k in ['x', 'y', 'width', 'height'])
        rx = min(float(a.get('rx', a.get('ry', 0))), w/2)
        ry = min(float(a.get('ry', a.get('rx', 0))), h/2)
        if not rx or not ry:
            return f'M{num(x)} {num(y)}h{num(w)}v{num(h)}H{num(x)}Z'
        return (f'M{num(x+rx)} {num(y)}H{num(x+w-rx)}a{num(rx)} {num(ry)} 0 0 1 {num(rx)} {num(ry)}'
                f'V{num(y+h-ry)}a{num(rx)} {num(ry)} 0 0 1 {num(-rx)} {num(ry)}'
                f'H{num(x+rx)}a{num(rx)} {num(ry)} 0 0 1 {num(-rx)} {num(-ry)}'
                f'V{num(y+ry)}a{num(rx)} {num(ry)} 0 0 1 {num(rx)} {num(-ry)}Z')
    raise ValueError(f'Unsupported SVG element: {tag}')


src = Path(__file__).resolve().parents[1] / 'src'
target = src / 'components/icons'
control_icons = ('chevron-down', 'chevron-right', 'chevron-up', 'circle-check', 'circle-question-mark', 'circle-x', 'download', 'file-text', 'info', 'triangle-alert', 'x')
controls = src / 'components/controlIcons.ts'
target.mkdir(parents=True, exist_ok=True)
with tarfile.open(fileobj=io.BytesIO(archive), mode='r:gz') as package:
    license_text = package.extractfile('package/LICENSE').read().decode()
    icons = {}
    for member in package.getmembers():
        if not member.name.startswith('package/icons/') or not member.name.endswith('.svg'):
            continue
        svg = ET.fromstring(package.extractfile(member).read())
        if svg.attrib.get('viewBox') != '0 0 24 24':
            raise ValueError(f'Unexpected viewBox: {member.name}')
        icons[Path(member.name).stem] = [path(element) for element in svg]
    (target / 'LICENSE.lucide').write_text(license_text)
    header = '/*!\n * @license Lucide ' + VERSION + '\n' + ''.join(' * ' + line + '\n' for line in license_text.splitlines()) + ' */\n'
    source = header + '// Generated by scripts/import-lucide.py; do not edit by hand.\n'
    source += 'export const lucidePaths = ' + json.dumps(dict(sorted(icons.items())), indent=2) + ';\n'
    source += '\nexport type NIconName = keyof typeof lucidePaths;\n'
    (target / 'lucide.ts').write_text(source)
    source = header + '// Generated by scripts/import-lucide.py; do not edit by hand.\n'
    source += "import type { IconOutline } from './iconImage';\n\n"
    source += 'const paths = ' + json.dumps({name: icons[name] for name in control_icons}, indent=2) + ';\n\n'
    source += '''export function controlIcon(name: string): IconOutline | undefined {
  return Object.hasOwn(paths, name) ? { paths: paths[name as keyof typeof paths], viewBox: 24 } : undefined;
}
'''
    controls.write_text(source)
subprocess.run(['bun', 'fmt', str(target / 'lucide.ts'), str(controls)], check=True)
print(f'Vendored {len(icons)} Lucide {VERSION} icons, including upstream aliases, into {target}')
